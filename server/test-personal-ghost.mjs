import assert from 'node:assert/strict';
import {build} from 'esbuild';
const load=async path=>{const r=await build({entryPoints:[path],bundle:true,format:'esm',platform:'node',write:false});return import('data:text/javascript;base64,'+Buffer.from(r.outputFiles[0].text).toString('base64'));};
const {personalGhostStore}=await load('host/ghost-store.ts');
const {resolveRaceControls}=await load('server/control-validation.ts');
const {classifyControl}=await load('games/sparking-stars/controls.ts');
const {ghostKey,makeGhost}=await load('games/sparking-stars/ghost.ts');
const memory=new Map(),storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const ghost=makeGhost([[0,288,312],[1000,280,300],[2000,270,280]]);
const store=personalGhostStore(storage,'0xabc','7730','rules1');
assert.equal(store.save(6,'training','feet',ghost,'touch').saved,true);
const key=ghostKey('7730',6,'training','feet','rules1','touch');
assert.deepEqual(personalGhostStore(storage,'0xABC','7730','rules1').read()[key],ghost,'reload retains a copy');
store.save(6,'training','feet',makeGhost([[0,288,312],[3000,250,250]]),'touch');assert.equal(store.read()[key].ms,2000,'slower lap cannot replace best');
store.save(6,'training','feet',makeGhost([[0,288,312],[1000,250,250]]),'desktop');assert.equal(store.read()[key].ms,2000,'desktop ghost remains separate');
assert.deepEqual(personalGhostStore(storage,'0xdef','7730','rules1').read(),{});
assert.deepEqual(personalGhostStore(storage,'0xabc','7731','rules1').read(),{});
assert.deepEqual(personalGhostStore(storage,'0xabc','7730','rules2').read(),{});
assert.throws(()=>store.save(6,'free','feet',ghost,'touch'));
assert.throws(()=>store.save(6,'training','feet',{ms:2000,points:[[0,288,312],[2000,9999,0]]},'touch'));
const blocked=personalGhostStore({getItem:()=>{throw Error('blocked');},setItem:()=>{throw Error('quota');}},'x','1','r');
assert.deepEqual(blocked.read(),{});assert.equal(blocked.save(1,'training','feet',ghost,'touch').saved,false);
for(const k of memory.keys())memory.set(k,'{"broken":');assert.deepEqual(store.read(),{});
assert.equal(classifyControl('touch','mouse'),'desktop');assert.equal(classifyControl('desktop','touch'),'desktop');
assert.equal(resolveRaceControls('touch','touch',[{ms:0,kind:'touch'}],2000),'touch');
assert.equal(resolveRaceControls('touch','desktop',[{ms:0,kind:'touch'},{ms:1500,kind:'mouse'}],2000),'desktop');
assert.throws(()=>resolveRaceControls('touch','touch',[{ms:0,kind:'touch'},{ms:1500,kind:'mouse'}],2000),'phone + mouse cannot remain tactile');
assert.throws(()=>resolveRaceControls('desktop','touch',[{ms:0,kind:'touch'}],2000));
assert.throws(()=>resolveRaceControls('touch','touch',[],2000));
assert.throws(()=>resolveRaceControls('touch','touch',[{ms:3000,kind:'touch'}],2000));
console.log('PASS persistent best ghost, wallet/Friend/rules/input isolation, damaged/quota storage; touch/mouse promotion and server rejection.');
