import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {transform} from 'esbuild';
const {code}=await transform(await readFile(new URL('./leaderboard-model.ts',import.meta.url),'utf8'),{loader:'ts',format:'esm'});
const {rankLaps,preciseTime,periodStart}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const base={gen:3,mode:'training',equipment:'feet',tier:0,bonus:'none',finishedAt:Date.now()};
const laps=[['1',14500],['2',13900],['3',13900],['1',14400]].map(([friendId,ms],id)=>({...base,friendId,ms,id}));
const ranked=rankLaps(laps);
assert.deepEqual(ranked.map(l=>l.rank),[1,1,3]);
assert.deepEqual(ranked.map(l=>l.gap),[0,0,500]);
assert.equal(ranked.length,3);
assert.equal(preciseTime(13900),'13.900 s');
assert.equal(preciseTime(14400-13900),'0.500 s');
assert.deepEqual(rankLaps([]),[]);
const now=Date.parse('2026-10-01T12:00:00Z');
assert.equal(periodStart('week',now),Date.parse('2026-09-28T00:00:00Z'));
assert.equal(periodStart('month',now),Date.parse('2026-10-01T00:00:00Z'));
assert.equal(periodStart('day',now),Date.parse('2026-10-01T00:00:00Z'));
console.log('Ties, best lap per Friend, exact gaps and UTC calendar boundaries passed');
